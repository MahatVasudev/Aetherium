use std::collections::HashSet;
use std::sync::OnceLock;

use crate::CONFIG_DIR;

static STOPWORD_SET: OnceLock<HashSet<String>> = OnceLock::new();

pub fn stopwords() -> &'static HashSet<String> {
    STOPWORD_SET.get_or_init(|| {
        let mut set: HashSet<String> = STOPWORDS.iter().map(|s| s.to_string()).collect();

        if let Some(config_dir) = CONFIG_DIR.as_ref() {
            let path = config_dir.join("stopwords.txt");
            if path.exists() {
                if let Ok(content) = std::fs::read_to_string(path) {
                    for line in content.lines() {
                        let word = line.trim().to_lowercase();
                        if !word.is_empty() && !word.starts_with("#") {
                            set.insert(word);
                        }
                    }
                }
            }
        }

        set
    })
}

